#pragma once

#include <memory>
#include <iostream>
#include <sqlite3.h>
#include <boost/asio.hpp>

using boost::asio::ip::tcp;

/**
 * @brief Структура для хранения информации о подключённом клиенте
 */
struct clientInfo {
    std::shared_ptr<tcp::socket> socket;  // Умный указатель на сокет клиента
    std::string username;                  // Имя пользователя
};

/**
 * @brief Глобальные переменные для управления клиентами
 * @note Все операции с этими переменными должны быть защищены мьютексом clients_mutex
 */
extern std::vector<clientInfo> clients;      // Вектор всех подключённых клиентов
extern std::mutex clients_mutex;             // Мьютекс для потокобезопасного доступа к clients


//=============================================================================
// Функции для работы с базой данных
//=============================================================================

/**
 * @brief Инициализирует подключение к базе данных SQLite
 * @return Указатель на объект базы данных
 * @note В случае ошибки возвращает nullptr и выводит сообщение об ошибке
 */
sqlite3* database_init();

/**
 * @brief Сохраняет сообщение в базу данных
 * @param from_user Отправитель сообщения
 * @param to_user   Получатель сообщения (для личных сообщений)
 * @param message   Текст сообщения
 * @param is_private Флаг: true - личное сообщение, false - публичное
 * @param db        Указатель на объект базы данных
 */
void save_message(const std::string& from_user, const std::string& to_user, 
                  const std::string& message, bool is_private, sqlite3* db);

/**
 * @brief Загружает историю сообщений для пользователя
 * @param username Имя пользователя
 * @param socket   Сокет для отправки истории
 * @param db       Указатель на объект базы данных
 * @param limit    Максимальное количество сообщений для загрузки (по умолчанию 10)
 * 
 * @details Загружает последние N сообщений, адресованных пользователю,
 *          включая публичные сообщения и личные, отправленные ему.
 */           
void load_messages(const std::string& username, std::shared_ptr<tcp::socket> socket, 
                   sqlite3* db, int limit = 10);

/**
 * @brief Проверяет, является ли сообщение командой выхода
 * @param msg Входное сообщение от клиента
 * @return true Если после нормализации сообщение равно "q" или "quit"
 * 
 */
bool is_quit(const std::string& msg);


//=============================================================================
// Функции для работы с клиентами
//=============================================================================

/**
 * @brief Обрабатывает подключение клиента
 * @param socket Умный указатель на сокет клиента
 * 
 * @details Функция:
 *          1. Запрашивает имя пользователя
 *          2. Загружает историю сообщений
 *          3. Входит в цикл приёма и обработки сообщений
 *          4. Обрабатывает команды выхода и отключает клиента
 */
void handle_client(std::shared_ptr<tcp::socket> socket);           // Обработка клиента
